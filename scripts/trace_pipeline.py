"""Execute demonstrations, record real component evidence, and publish a trace report."""
import json
from pathlib import Path
from datetime import datetime,timezone
from analytics_agent.config import PROJECT_ROOT
from analytics_agent.models import AccessScope
from analytics_agent.platform import PlatformAgent,PlatformContext
from analytics_agent.sales_parser import SALES_DEMOS
from analytics_agent.exports import csv_report,excel_report,pdf_report


def run():
    output=PROJECT_ROOT/"reports"
    output.mkdir(exist_ok=True)
    agent=PlatformAgent(scope=AccessScope(domains=("usage","sales")))
    context=PlatformContext(); answers=[]
    for question in SALES_DEMOS:
        answer=agent.run(question,context,mode="demo")
        if answer.status!="ok": raise RuntimeError(f"Sales demo failed: {answer.message}")
        context=answer.context
        answers.append({"question":question,"answer":answer.model_dump(mode="json")})
    report={"generated_at_utc":datetime.now(timezone.utc).isoformat(),"status":"pass",
        "mode":"explicit deterministic synthetic demo","registered_domains":["usage","sales"],
        "demonstrations":answers,"limitations":["No actual enterprise database or messaging channel is connected.",
        "Public demo makes no LLM calls; sales tool calling is mocked in automated tests.",
        "Cross-domain joins require a separate approved contract and currently prompt clarification."]}
    (output/"sales_pipeline_trace.json").write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    sample=agent.run(SALES_DEMOS[0],mode="demo")
    deliverable=PROJECT_ROOT/"output"/"pdf"
    deliverable.mkdir(parents=True,exist_ok=True)
    (deliverable/"Synthetic_Sales_Pipeline_Report.pdf").write_bytes(pdf_report(sample))
    # CSV/Excel downloads are generated by the app in memory; no hosted disk writes.
    return {"status":"pass","sales_demonstrations":len(answers),"components_per_trace":7,
        "example_baseline":sample.results[0].baseline,"example_current":sample.results[0].current,
        "trace_report":"reports/sales_pipeline_trace.json","pdf_report":"output/pdf/Synthetic_Sales_Pipeline_Report.pdf"}


if __name__ == "__main__": print(json.dumps(run(),indent=2))
